integer_value = int(input("Enter an integer value: "))
float_value = float(input("Enter a decimal value: "))

string_value = str(integer_value)
boolean_value = bool(integer_value)

print("\nInteger:", integer_value)
print("Type:", type(integer_value))

print("\nFloat:", float_value)
print("Type:", type(float_value))

print("\nString:", string_value)
print("Type:", type(string_value))

print("\nBoolean:", boolean_value)
print("Type:", type(boolean_value))
